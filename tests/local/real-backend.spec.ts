  await page.getByPlaceholder('Nome della campagna').fill(`Tavolo locale ${stamp}`)
  await page.getByRole('button', { name: 'Salva impostazioni' }).click()
  await expect(page.locator('.campaign-settings').getByRole('status').first()).toHaveText('Impostazioni salvate.')
  expect((await requestJson(request, master, 'GET', `/campaigns/${cid}`)).name).toBe(`Tavolo locale ${stamp}`)
  await page.locator('summary').filter({ hasText: 'Crea un invito con limiti' }).click()
