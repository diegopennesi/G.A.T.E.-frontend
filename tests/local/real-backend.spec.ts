  await page.getByRole('button', { name: 'Crea invito', exact: true }).click()
  await expect(page.getByLabel('Nuovo codice invito')).not.toHaveValue('')
  const token = await page.getByLabel('Nuovo codice invito').inputValue()
  await requestJson(request, player, 'POST', `/campaigns/tokens/${token}/apply`, {})
  await page.goto(`/homepage/gate/app/campagna-accessi?campaignId=${cid}`)
  await page.getByRole('button', { name: 'Approva accesso' }).click()
  await expect(page.locator('.approvals-page').getByRole('status')).toContainText('richiesta approvata')
  expect((await requestJson(request, player, 'GET', '/campaigns/me/memberships')).find((item: {campaignId: string}) => item.campaignId === cid).memberStatus).toBe('APPROVED')
  await page.goto(`/homepage/gate/app/campagna?campaignId=${cid}`)
  await page.getByRole('button', { name: 'Giocatore collaudo locale', exact: true }).click()
  await page.getByRole('button', { name: 'Sospendi accesso' }).click()
  const dialog = page.getByRole('dialog', { name: 'Sospendi accesso alla campagna' })
  await dialog.getByLabel('Motivo della moderazione').fill('Pausa del collaudo')
  await dialog.getByRole('button', { name: 'Conferma', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Rimuovi sospensione' })).toBeVisible()
  await page.getByRole('button', { name: 'Rimuovi sospensione' }).click()
  await expect(page.getByRole('button', { name: 'Sospendi accesso' })).toBeVisible()
  const forbidden = await request.fetch(`${api}/campaigns/${cid}`, { method: 'PATCH', data: { name: 'Non consentito' }, headers: { Authorization: `Bearer ${player.accessToken}`, 'X-GATE-Realm-Code': 'gate' } })
  expect(forbidden.status()).toBe(403)
  await page.goto(`/homepage/gate/app/stanze?campaignId=${cid}`)
  await page.getByRole('button', { name: 'Crea stanza', exact: true }).click()
  await page.getByLabel('Nome della stanza').fill('La taverna locale')
  await page.getByRole('button', { name: 'Crea stanza', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Stanza creata.')
  expect((await requestJson(request, master, 'GET', `/campaigns/${cid}/rooms`)).some((room: {name: string}) => room.name === 'La taverna locale')).toBeTruthy()
  const character = await requestJson(request, player, 'POST', `/campaigns/${cid}/characters`, { name: 'Esploratore locale', isNpc: false })
  const mission = await requestJson(request, master, 'POST', `/campaigns/${cid}/missions`, { title: 'La missione locale', sessionAt: new Date(Date.now() + 3 * 86400000).toISOString(), closesAt: new Date(Date.now() + 2 * 86400000).toISOString(), autoReopenOnDrop: true })
  const playerContext = await browser.newContext()
  const playerPage = await playerContext.newPage()
  playerPage.on('pageerror', error => browserErrors.push(error.message))
  await authenticate(playerPage, player, cid)
  await playerPage.goto(`http://127.0.0.1:5180/homepage/gate/app/missioni?campaignId=${cid}&missionId=${mission.id}`)
  await expect(playerPage.getByRole('button', { name: 'Cambia campagna' })).toBeVisible()
  await expect(playerPage.getByRole('heading', { name: 'La missione locale', exact: true })).toBeVisible()
  await playerPage.getByRole('button', { name: 'Titolare', exact: true }).click()
  await expect(playerPage.getByRole('button', { name: 'Titolare', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect((await requestJson(request, player, 'GET', `/campaigns/${cid}/missions/${mission.id}/participants`))[0].characterId).toBe(character.id)
  await mkdir('local-test-results/screenshots', { recursive: true })
